CREATE TABLE google_challenges (
    hash VARCHAR(64) PRIMARY KEY,
    purpose VARCHAR(16) NOT NULL,
    account_id VARCHAR(255) REFERENCES accounts(id) ON DELETE CASCADE,
    verifier VARCHAR(128),
    expires_at BIGINT NOT NULL
);
CREATE INDEX idx_google_challenges_expiry ON google_challenges(expires_at);
CREATE TABLE google_drive_connections (
    account_id VARCHAR(255) PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    encrypted_refresh_token TEXT NOT NULL,
    email VARCHAR(254) NOT NULL
);
CREATE TABLE admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id VARCHAR(255) NOT NULL,
    action VARCHAR(64) NOT NULL,
    target_id VARCHAR(255) NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX idx_admin_audit_created ON admin_audit(created_at);
