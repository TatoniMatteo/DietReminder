-- PostgreSQL is the authoritative server database. IDs and timestamps keep the
-- existing API representation; account ownership is enforced by foreign keys.
CREATE TABLE accounts (
    id VARCHAR(255) PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    username VARCHAR(100) NOT NULL
);
CREATE TABLE account_tokens (
    hash VARCHAR(64) PRIMARY KEY,
    account_id VARCHAR(255) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    purpose VARCHAR(255) NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX idx_token_account ON account_tokens(account_id);
CREATE TABLE user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL UNIQUE REFERENCES accounts(id) ON DELETE CASCADE,
    username VARCHAR(255) NOT NULL,
    daily_calorie_goal INTEGER NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE TABLE sync_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(255) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    data_type VARCHAR(255) NOT NULL,
    payload TEXT NOT NULL,
    timestamp BIGINT NOT NULL,
    request_id VARCHAR(64),
    CONSTRAINT uk_sync_user_request UNIQUE(user_id, request_id)
);
CREATE INDEX idx_sync_user_id ON sync_records(user_id, id);
CREATE TABLE cloud_workspaces (
    account_id VARCHAR(255) PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    revision BIGINT NOT NULL,
    payload TEXT NOT NULL
);
CREATE TABLE workspace_commits (
    id VARCHAR(255) PRIMARY KEY,
    account_id VARCHAR(255) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    request_id VARCHAR(255) NOT NULL,
    revision BIGINT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    CONSTRAINT uk_workspace_request UNIQUE(account_id, request_id)
);
