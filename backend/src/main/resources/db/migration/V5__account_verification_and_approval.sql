-- Existing accounts retain access; new registrations must complete enrollment.
ALTER TABLE accounts ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE accounts ALTER COLUMN email_verified SET DEFAULT FALSE;
ALTER TABLE accounts ADD COLUMN enrollment_status VARCHAR(32) NOT NULL DEFAULT 'APPROVED'
    CHECK (enrollment_status IN ('PENDING_EMAIL', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED'));
ALTER TABLE accounts ALTER COLUMN enrollment_status SET DEFAULT 'PENDING_EMAIL';
ALTER TABLE accounts ADD COLUMN permissions TEXT NOT NULL DEFAULT 'WORKSPACE_READ,DIETS_WRITE,SHOPPING_WRITE,PROFILE_WRITE,BACKUP_MANAGE';
ALTER TABLE accounts ADD COLUMN review_reason VARCHAR(1000);
ALTER TABLE accounts ADD COLUMN enrollment_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE accounts ADD COLUMN admin_introduction_acknowledged BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE accounts ADD CONSTRAINT approved_email_required CHECK (enrollment_status <> 'APPROVED' OR email_verified);
ALTER TABLE accounts ADD CONSTRAINT administrator_enrollment CHECK (role <> 'ADMIN' OR enrollment_status IN ('PENDING_EMAIL', 'APPROVED'));

CREATE TABLE enrollment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id VARCHAR(255) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    status VARCHAR(32) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX idx_enrollment_events_account ON enrollment_events(account_id, id);
CREATE TABLE account_mail_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id VARCHAR(255) NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    kind VARCHAR(32) NOT NULL,
    recipient VARCHAR(254) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) * 1000)::BIGINT,
    next_attempt_at BIGINT NOT NULL,
    sent_at BIGINT
);
CREATE INDEX idx_account_mail_due ON account_mail_outbox(next_attempt_at) WHERE sent_at IS NULL;

CREATE INDEX idx_accounts_enrollment ON accounts(enrollment_status, created_at DESC);
